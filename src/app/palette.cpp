ThemePalette _make(const std::array<std::uint32_t, kRoleCount>& hex)
{
    ThemePalette palette;
    for (std::size_t i = 0; i < kRoleCount; ++i) {
        palette.colors[i] = srgb(hex[i]);
    }
    return palette;
}

